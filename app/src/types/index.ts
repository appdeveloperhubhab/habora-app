/** Дата без времени в локальной таймзоне пользователя: `YYYY-MM-DD`. */
export type IsoDate = string

/** День недели, 0 = понедельник … 6 = воскресенье. */
export type Weekday = 0 | 1 | 2 | 3 | 4 | 5 | 6

/**
 * Расписание привычки. Пользователь выбирает один из двух режимов:
 * конкретные дни недели либо просто число раз в неделю без привязки к дням.
 */
export type ScheduleType = 'weekdays' | 'frequency'

export interface HabitSchedule {
  type: ScheduleType
  /** Значимо при type === 'weekdays'. */
  days: Weekday[]
  /** Значимо при type === 'frequency'. */
  timesPerWeek: number
}

export interface Habit {
  id: string
  name: string
  description: string
  /** Индивидуальный цвет привычки в hex, из палитры. */
  color: string
  /** Эмодзи (например, `💧`) либо id иконки из встроенного набора (`ic:water`). */
  icon: string
  schedule: HabitSchedule
  /** Цель по длине серии в днях; null — цель не задана. */
  streakGoal: number | null
  /** Заливать ли карточку цветом привычки. Выключено — карточка нейтральная. */
  tinted: boolean
  /**
   * Длительность в секундах для привычек вроде «медитация 10 минут»
   * или «планка 40 секунд»; null — таймера нет.
   *
   * В секундах, а не в минутах: короткие упражнения измеряются десятками
   * секунд, и округление до минуты сделало бы таймер для них бесполезным.
   */
  durationSec: number | null
  /**
   * Время напоминания `ЧЧ:ММ` в сутках человека; null — не напоминать.
   *
   * Одно на всю привычку, а не своё у каждого участника: в совместной
   * привычке договариваются делать вместе, и разное время у каждого
   * означало бы две разные привычки под одним названием.
   */
  remindAt: string | null
  sortOrder: number
  createdAt: string
  /** Кто завёл привычку. Менять и удалять её у всех вправе только он. */
  ownerId?: number
  /** Участники совместной привычки; у обычной — один создатель. */
  members?: HabitMember[]
}

export type HabitInput = Omit<Habit, 'id' | 'createdAt' | 'sortOrder' | 'ownerId' | 'members'>

/**
 * Участник привычки. У обычной привычки он один — тот, кто её завёл;
 * у совместной их несколько, и каждый отмечается за себя.
 */
export interface HabitMember {
  userId: number
  firstName: string
  username: string | null
  photoUrl: string | null
  /** Завёл привычку: только он вправе её менять и удалять у всех. */
  isOwner: boolean
  doneToday: boolean
}

/**
 * Друг — человек, с которым есть хотя бы одна общая привычка.
 *
 * Отдельного списка друзей нет: связь возникает от участия в привычке и
 * исчезает вместе с ним. Отметки приходят только по общим привычкам —
 * делятся привычкой, а не аккаунтом.
 */
export interface Friend {
  userId: number
  firstName: string
  username: string | null
  photoUrl: string | null
  habits: { habitId: string; dates: IsoDate[] }[]
}

/**
 * Отметка выполнения за конкретный день. Хранится как факт: строка есть —
 * день выполнен, строки нет — не выполнен. Никаких счётчиков и флагов.
 */
export interface Entry {
  habitId: string
  date: IsoDate
}

/**
 * Запущенный таймер.
 *
 * Хранится момент старта, а не остаток: браузер останавливает счётчики в
 * неактивных вкладках, и таймер, уменьшающий остаток по тику, замирал бы,
 * как только приложение свернули. От времени старта остаток всегда можно
 * пересчитать заново.
 */
export interface ActiveTimer {
  /** Осталось от времён, когда таймер запускался и у задач. */
  kind: 'habit'
  id: string
  startedAt: string
  durationSec: number
  /** Момент постановки на паузу; null — идёт. */
  pausedAt: string | null
  /** Сколько миллисекунд суммарно провели на паузе. */
  pausedMs: number
}

export type ThemeMode = 'dark' | 'light'
export type Lang = 'ru' | 'en' | 'uk'

/**
 * Вид карточек в списке привычек. Применяется сразу ко всем привычкам,
 * переключается в режиме «Порядок».
 *
 * Три шага одной шкалы — от ближнего взгляда к дальнему: `week` — узкая
 * строка с текущей неделей, `month` — плитка по две карточки в ряд с
 * календарём месяца, `year` — карточка во всю ширину с годом целиком.
 */
export type CardView = 'week' | 'month' | 'year'

/**
 * Фон приложения: чистый цвет темы или градиент из двух выбранных цветов.
 *
 * Были ещё подсветка акцентом и своя фотография — убраны как лишний выбор:
 * подсветка почти не отличалась от чистого фона, а фотография спорила с
 * карточками и мешала их читать.
 */
export type BackgroundKind = 'none' | 'gradient'

export interface Settings {
  theme: ThemeMode
  lang: Lang
  accentColor: string
  cardView: CardView
  backgroundKind: BackgroundKind
  gradientFrom: string
  gradientTo: string
  /** Пройден ли онбординг первого запуска. */
  onboarded: boolean
  /** Запущенный таймер; null — ничего не идёт. Одновременно может быть только один. */
  timer: ActiveTimer | null
  /**
   * Слать ли вечернее напоминание о невыполненных привычках в чат с ботом.
   *
   * Хранится в настройках, а не отдельным полем у пользователя: это такая же
   * настройка приложения, как тема или язык, и человек ищет её там же.
   */
  reminders: boolean
  /** Ключи уже отпразднованных вех — чтобы не показывать салют повторно. */
  celebrated: string[]
  /** Видел ли пользователь подсказку у кнопки отметки. */
  hintSeen: boolean
}
