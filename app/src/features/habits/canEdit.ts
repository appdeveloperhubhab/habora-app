import type { Habit } from '../../types'
import { currentUserId } from '../../lib/telegram'

/**
 * Вправе ли человек править эту привычку.
 *
 * Править вправе только тот, кто её завёл: у остальных сервер отвечает на
 * правку отказом. Приглашённому карандаш и пункт «Редактировать» показывались
 * наравне со всеми, но открытая форма ничего не сохраняла — нажатие галочки
 * просто не давало ничего. Кнопка, которая ничем не отличается от рабочей и
 * при этом не работает, хуже отсутствующей: человек считает, что сломалось
 * приложение.
 *
 * Решение живёт в одном месте, а не у каждой кнопки: право на правку
 * спрашивают из списка и с экрана привычки, и два разных ответа означали бы,
 * что откуда-то в форму всё-таки можно попасть.
 */
export function canEdit(habit: Habit): boolean {
  /*
   * Без сервера привычка своя по определению: там нет ни участников, ни
   * чужих привычек, а имени пользователя Telegram может не быть вовсе.
   */
  if (habit.ownerId === undefined) return true

  const me = currentUserId()
  return me !== null && me === habit.ownerId
}
