/**
 * Цвета задач по приоритету.
 *
 * Важные — янтарные, а не красные: красный в интерфейсе занят под удаление и
 * ошибки, и если красить им обычную важную задачу, он перестаёт значить
 * опасность. Янтарный цепляет взгляд, но не кричит.
 *
 * Обычные — сине-голубые: спокойный тон, максимально далёкий от янтарного,
 * так что две группы не спутать даже боковым зрением.
 *
 * Оба цвета заданы жёстко и не зависят от акцента приложения: иначе
 * пользователь с оранжевым акцентом получил бы две неразличимые группы.
 */
export const TASK_COLORS = {
  normal: '#4C8DFF',
  important: '#FFA524',
} as const

/**
 * Цвет по умолчанию для новой привычки — берётся по кругу, чтобы соседние
 * различались. Порядок не совпадает с порядком в палитре: там цвета идут по
 * кругу спектра, и подряд заведённые привычки получали бы соседние оттенки.
 */
export function nextDefaultColor(usedCount: number): string {
  const spread = [
    '#0A84FF', '#FF9F0A', '#32D74B', '#BF5AF2', '#FF453A',
    '#40C8E0', '#FFD60A', '#FF6482', '#5E5CE6', '#98989D',
  ]
  return spread[usedCount % spread.length]
}
