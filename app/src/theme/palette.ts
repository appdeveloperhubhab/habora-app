/**
 * Цвет привычки: основной тон плюс пара оттенков для градиента.
 *
 * Градиент задан явными концами, а не выведен из основного тона осветлением.
 * Механическое «светлее сверху, темнее снизу» даёт грязь: у жёлтого светлый
 * конец уходит в белёсый, у синего тёмный — в чёрный. Здесь у каждого цвета
 * концы подобраны так, чтобы переход шёл ещё и по тону — тёплый край к
 * тёплому, холодный к холодному, — и плитка выглядела объёмной, а не
 * закрашенной с прозрачностью.
 */
export interface HabitColor {
  /** Что хранится у привычки и красит карточки, клетки и графики. */
  value: string
  /** Светлый конец градиента — верхний левый угол плитки. */
  from: string
  /** Тёмный конец — нижний правый. */
  to: string
}

