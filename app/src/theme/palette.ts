/** Серый цвет набора — к нему сводятся оттенки, у которых тона почти нет. */
const GREY = '#8A94A6'

/** Цвет в HSL: тон 0…360, насыщенность и светлота 0…1. */
function toHsl(hex: string): { h: number; s: number; l: number } {
  const r = parseInt(hex.slice(1, 3), 16) / 255
  const g = parseInt(hex.slice(3, 5), 16) / 255
  const b = parseInt(hex.slice(5, 7), 16) / 255

  const max = Math.max(r, g, b)
  const min = Math.min(r, g, b)
  const span = max - min
  const l = (max + min) / 2

  if (span === 0) return { h: 0, s: 0, l }

  const s = l > 0.5 ? span / (2 - max - min) : span / (max + min)
  let h: number
  if (max === r) h = ((g - b) / span + (g < b ? 6 : 0)) * 60
  else if (max === g) h = ((b - r) / span + 2) * 60
  else h = ((r - g) / span + 4) * 60

  return { h, s, l }
}

/**
 * Ближайший цвет набора к произвольному оттенку.
 *
 * Нужен привычкам, заведённым до сокращения палитры: их цвета в наборе больше
 * нет, а показывать одиннадцатую плитку нельзя — ряд перестаёт быть ровным.
 * Поэтому старый оттенок заменяется самым похожим из десяти: малиновый станет
 * красным, а не случайным цветом, и привычка останется узнаваемой.
 *
 * Похожесть считается по тону, а не по расстоянию между каналами RGB. В RGB
 * решает светлота: все десять цветов набора средней яркости, тёмный оттенок
 * далёк от каждого из них примерно одинаково, и победитель выходил случайным —
 * тёмный графит становился красным, а хвойный серым. Тон же у тёмного и
 * светлого зелёного один и тот же, и именно он отвечает за узнавание.
 *
 * Насыщенность входит слабой поправкой, светлота — ещё слабее: они уточняют
 * выбор внутри одного тона, но не должны его перебивать. Совсем блёклые
 * оттенки уходят в серый: тон у них есть, но глазом он не читается.
 */
export function nearestHabitColor(hex: string): string {
  if (!/^#[0-9a-f]{6}$/i.test(hex)) return HABIT_COLORS[0].value

  const source = toHsl(hex)
  if (source.s < 0.16) return GREY

  let best = HABIT_COLORS[0].value
  let bestScore = Infinity
  for (const color of HABIT_COLORS) {
    // Серый не участвует в разборе по тону: тона у него нет, и любой оттенок
    // оказывался бы от него на случайном расстоянии.
    if (color.value === GREY) continue

    const target = toHsl(color.value)
    const gap = Math.abs(source.h - target.h)
    const hue = Math.min(gap, 360 - gap) / 180

    /*
     * Тон весит на порядок больше остального. При меньшем весе блёклый
     * оттенок притягивался к бледному цвету набора мимо своего тона:
     * стальной синий уходил в бирюзовый только потому, что бирюзовый
     * в наборе менее насыщенный, чем синий.
     */
    const score = hue ** 2 * 20 + (source.s - target.s) ** 2 * 0.5 + (source.l - target.l) ** 2 * 0.5
    if (score < bestScore) {
      bestScore = score
      best = color.value
    }
  }
  return best
}

/**
 * Цвета задач по приоритету.
 *
 * Важные — янтарные, а не красные: красный в интерфейсе занят под удаление и
 * ошибки, и если красить им обычную важную задачу, он перестаёт значить
 * опасность. Янтарный цепляет взгляд, но не кричит.
 *
 * Обычные — сине-голубые: спокойный тон, максимально далёкий от янтарного,
 * так что две группы не спутать даже боковым зрением.
 *
 * Оба цвета заданы жёстко и не зависят от акцента приложения: иначе
 * пользователь с оранжевым акцентом получил бы две неразличимые группы.
 */
