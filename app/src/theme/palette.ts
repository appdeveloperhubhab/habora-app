/**
 * Цвет по умолчанию для новой привычки — берётся по кругу, чтобы соседние
 * различались. Порядок не совпадает с порядком в палитре: там цвета идут по
 * кругу спектра, и подряд заведённые привычки получали бы соседние оттенки.
 */
export function nextDefaultColor(usedCount: number): string {
  const spread = [
    '#4796F0', '#F79A3E', '#4FC98D', '#A166EC', '#F2554A',
    '#42C0BB', '#F7C846', '#F072AC', '#6F79EC', '#8A94A6',
  ]
  return spread[usedCount % spread.length]
}
