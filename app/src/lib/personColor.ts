/**
 * Цвет человека, выведенный из его имени.
 *
 * Не случайный и не из общей палитры привычек: у одного и того же человека
 * он должен быть один и тот же при каждой отрисовке, без отдельного поля
 * в базе. Общий источник для аватарки и для меток в совместных сетках —
 * значит, в обоих местах Аня остаётся одного и того же цвета.
 */
export function personColor(name: string): string {
  const hue = [...name].reduce((sum, char) => sum + char.codePointAt(0)!, 0) % 360
  return `hsl(${hue} 52% 46%)`
}
