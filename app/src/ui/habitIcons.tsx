/**
 * Рисует иконку привычки: силуэт из набора либо эмодзи, если он сохранён
 * у привычки с тех времён, когда его можно было выбрать с клавиатуры.
 */
export function HabitIcon({ icon, size = 24 }: { icon: string; size?: number }) {
  if (!icon.startsWith(ICON_PREFIX)) {
    return (
      <span style={{ fontSize: size * 0.86, lineHeight: 1 }} aria-hidden="true">
        {icon}
      </span>
    )
  }

  const path = P[icon.slice(ICON_PREFIX.length)] ?? P.star
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
      {path}
    </svg>
  )
}
