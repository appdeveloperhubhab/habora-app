/**
 * Рисует иконку привычки: путь из набора либо эмодзи, если пользователь
 * выбрал его с системной клавиатуры.
 */
export function HabitIcon({ icon, size = 24 }: { icon: string; size?: number }) {
  if (!icon.startsWith(ICON_PREFIX)) {
    return (
      <span style={{ fontSize: size * 0.86, lineHeight: 1 }} aria-hidden="true">
        {icon}
      </span>
    )
  }

  const path = P[icon.slice(ICON_PREFIX.length)] ?? P.star
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {path}
    </svg>
  )
}
