/**
 * Встроенный набор иконок для привычек — плотные, залитые силуэты на сетке
 * 24×24, а не контурные линии, как у иконок интерфейса.
 *
 * Разница намеренная. Иконка привычки стоит в цветном кружке размером с ноготь
 * и должна узнаваться мгновенно; контур на таком размере рассыпается на
 * отдельные штрихи и читается хуже сплошного пятна. Иконки же интерфейса
 * (кнопки, стрелки) остаются линейными: они не соревнуются за внимание.
 *
 * Фигурки людей нарисованы толстым штрихом с круглыми концами, а не заливкой:
 * руки и ноги — это линии, и заливка каждой конечности отдельной фигурой дала
 * бы тот же силуэт вчетверо более сложным путём.
 */

/** Штриховая часть иконки: конечности фигурок, дуги, тонкие детали. */
function S({ d, w = 2.3 }: { d: string; w?: number }) {
  return (
    <path
      d={d}
      fill="none"
      stroke="currentColor"
      strokeWidth={w}
      strokeLinecap="round"
      strokeLinejoin="round"
    />
  )
}

/** Кольцо: окружность штрихом, а не залитый круг. */
function R({ cx, cy, r, w = 2.1 }: { cx: number; cy: number; r: number; w?: number }) {
  return <circle cx={cx} cy={cy} r={r} fill="none" stroke="currentColor" strokeWidth={w} />
}

/**
 * Силуэт с настоящим отверстием: вложенные контуры вычитаются друг из друга.
 *
 * Дырку нельзя нарисовать фигурой цвета фона — иконка лежит на карточке
 * привычки, залитой её цветом, и такая «заглушка» была бы видна пятном.
 */
function H({ d }: { d: string }) {
  return <path d={d} fillRule="evenodd" clipRule="evenodd" />
}

/** Окружность как участок пути — нужна, чтобы вырезать круглое отверстие. */
function hole(cx: number, cy: number, r: number): string {
  return `M${cx} ${cy - r}a${r} ${r} 0 1 0 0 ${r * 2}a${r} ${r} 0 1 0 0 ${-r * 2}z`
}

